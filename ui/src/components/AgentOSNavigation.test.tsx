// @vitest-environment jsdom
import { act } from "react";
import { createRoot } from "react-dom/client";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import type { Company } from "@paperclipai/shared";
import type { FridayNavigation } from "@/lib/friday-navigation";
import { expect, it, vi } from "vitest";
import { AgentOSSidebar } from "./AgentOSNavigation";
vi.mock("./AgentOSBrand", () => ({ AgentOSBrand: () => null }));
vi.mock("./AgentOSAccountMenu", () => ({ AgentOSAccountMenu: () => null }));
vi.mock("@/api/projects", () => ({ projectsApi: { list: (companyId: string) => Promise.resolve([{ id: `${companyId}-project`, name: `${companyId} project` }, { id: `${companyId}-archived`, name: "Archived project", archivedAt: "2026-11-01" }]) } }));
vi.mock("@/api/departments", () => ({ departmentKey: (id: string) => ["departments", id], departmentsApi: { list: (companyId: string) => Promise.resolve([{ id: `${companyId}-department`, name: `${companyId} department`, projectIds: [`${companyId}-project`] }]) } }));
it("progressively expands the scoped hierarchy and keeps the footer through Audit navigation", async () => {
  const client = new QueryClient({ defaultOptions: { queries: { retry: false } } }), host = document.createElement("div"); document.body.append(host);
  const root = createRoot(host), navigate = vi.fn();
  const companies = [{ id: "one", name: "First venture" }, { id: "two", name: "Second venture" }] as Company[];
  const render = (companyId: string, view: Partial<FridayNavigation> = {}) => root.render(<QueryClientProvider client={client}><AgentOSSidebar companies={companies} view={{ panel: "team", companyId, ...view }} navigate={navigate} /></QueryClientProvider>);
  const button = (label: string) => [...host.querySelectorAll("button")].find(item => item.textContent === label)!;
  const settle = async () => { await act(async () => { await new Promise(resolve => setTimeout(resolve, 10)); }); };
  try {
    await act(async () => render("one"));
    expect(host.querySelector('[aria-label="Departments and their projects"]')).toBeNull();
    expect(host.querySelector('[aria-label="Company projects"]')).toBeNull();
    expect(button("Departments").getAttribute("aria-expanded")).toBe("false");
    expect(button("Projects").getAttribute("aria-expanded")).toBe("false");
    const workspace = [...host.querySelectorAll('nav[aria-label="Workspace"] button')].map(button => button.textContent);
    expect(workspace.indexOf("Departments")).toBeLessThan(workspace.indexOf("Projects"));
    const footer = [...host.querySelectorAll('nav[aria-label="People, history and settings"] button')].map(button => button.textContent);
    expect(footer.slice(-2)).toEqual(["Saved displays", "Settings"]);
    expect([...host.querySelectorAll("button")].find(button => button.textContent === "Saved displays")?.querySelector("svg.lucide-monitor")).not.toBeNull();
    expect(host.textContent).not.toContain("Departments & projects");
    expect(host.textContent).not.toContain("Delete company");
    await act(async () => button("Departments").click());
    await settle();
    expect(button("Departments").getAttribute("aria-expanded")).toBe("true");
    expect(host.textContent).toContain("one department");
    expect(host.textContent).not.toContain("two department");
    const departmentTree = host.querySelector('[aria-label="Departments and their projects"]')!;
    const departmentToggle = departmentTree.querySelector<HTMLButtonElement>(".agentos-tree-toggle")!;
    expect(departmentToggle.getAttribute("aria-expanded")).toBe("false");
    await act(async () => departmentToggle.click());
    expect(navigate).toHaveBeenLastCalledWith({ panel: "projects", companyId: "one", departmentId: "one-department" });
    expect(departmentToggle.getAttribute("aria-expanded")).toBe("true");
    await act(async () => render("one", { panel: "work", projectId: "one-project", departmentId: "one-department" }));
    await act(async () => departmentToggle.click());
    expect(departmentToggle.getAttribute("aria-expanded")).toBe("false");
    expect(departmentToggle.nextElementSibling?.hasAttribute("hidden")).toBe(true);
    await act(async () => button("Departments").click());
    expect(host.querySelector('[aria-label="Departments and their projects"]')).toBeNull();
    await act(async () => button("Projects").click());
    await settle();
    const projectTree = host.querySelector('[aria-label="Company projects"]')!;
    expect(projectTree.textContent).toContain("one project");
    expect(projectTree.textContent).not.toContain("one department");
    expect(projectTree.textContent).not.toContain("Archived project");
    await act(async () => button("Projects").click());
    expect(host.querySelector('[aria-label="Company projects"]')).toBeNull();
    await act(async () => render("two"));
    expect(button("Projects").getAttribute("aria-expanded")).toBe("false");
    await act(async () => button("Projects").click());
    await settle();
    expect(host.textContent).toContain("two project");
    expect(host.textContent).not.toContain("one department");
    await act(async () => [...host.querySelectorAll("button")].find(button => button.textContent === "two project")!.click());
    expect(navigate).toHaveBeenLastCalledWith({ panel: "work", companyId: "two", departmentId: "two-department", projectId: "two-project", mode: "combined" });
    await act(async () => button("Audit trail").click());
    expect(navigate).toHaveBeenLastCalledWith({ panel: "activity", companyId: "two", scope: undefined, projectId: undefined });
    await act(async () => render("two", { panel: "activity" }));
    expect([...host.querySelectorAll('nav[aria-label="People, history and settings"] button')].map(item => item.textContent)).toEqual(["Workforce", "Audit trail", "Saved displays", "Settings"]);
    expect(button("Audit trail").getAttribute("aria-current")).toBe("page");
    await act(async () => [...host.querySelectorAll("button")].find(button => button.textContent === "Settings")!.click());
    expect(navigate).toHaveBeenLastCalledWith({ panel: "settings", companyId: "two" });
  } finally { await act(async () => root.unmount()); client.clear(); host.remove(); }
});
